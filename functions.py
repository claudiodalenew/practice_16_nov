def somma(a: int,b: int) -> int:
    '''la funzione somma riceve due argomenti e ritorna la somma degli argomenti'''
    return a+b

def sottrazione(a,b):
    return a-b

def moltiplicazione(a,b):
    '''la funzione moltiplicazione riceve due argomenti e ritorna il loro prodotto'''
    return a*b

def division(a,b):
    return a/b